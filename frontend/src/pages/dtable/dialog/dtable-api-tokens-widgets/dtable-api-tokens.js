import React, { Component } from 'react';
import PropTypes from 'prop-types';
import { gettext, mediaUrl } from '../../../../constants';
import { DTableEmptyTip } from 'dtable-ui-component';
import DTableApiTokenItem from './dtable-api-token-item';

class DtableApiTokens extends Component {

  constructor(props) {
    super(props);
    this.state = {
      isOpIconShown: false,
      highlight: false,
      isItemFreezed: false,
    };
  }

  onFreezedItem = () => {
    this.setState({ isItemFreezed: true });
  };

  onUnfreezedItem = () => {
    this.setState({ isItemFreezed: false });
  };

  render() {
    const { baseAPITokens } = this.props;
    const table = (
      <table>
        <thead>
          <tr>
            <th width="20%" className='pl-2'>{gettext('App name')}</th>
            <th width="55%">{gettext('API token')}</th>
            <th width="20%">{gettext('Generated by')}</th>
            <th width="5%">{/* Operations*/}</th>
          </tr>
        </thead>
        <tbody>
          {baseAPITokens.map((item) => {
            return (<DTableApiTokenItem
              key={item.api_token}
              item={item}
              isItemFreezed={this.state.isItemFreezed}
              onFreezedItem={this.onFreezedItem}
              onUnfreezedItem={this.onUnfreezedItem}
              deleteAPIToken={this.props.deleteAPIToken}
            />);
          })}
        </tbody>
      </table>
    );
    const emptyTip = (
      <DTableEmptyTip src={`${mediaUrl}img/no-items-tip.png`} text={gettext('No base API tokens')} />
    );

    return baseAPITokens.length === 0 ? emptyTip : table;
  }
}

DtableApiTokens.propTypes = {
  baseAPITokens: PropTypes.array,
  deleteAPIToken: PropTypes.func.isRequired
};

export default DtableApiTokens;
