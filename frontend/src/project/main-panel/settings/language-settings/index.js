import React, { useCallback, useEffect, useMemo, useState } from 'react';
import classnames from 'classnames';
import { CustomizeSelect } from '@/components';
import { gettext } from '@/constants';

import './index.css';

const LANGUAGE_OPTIONS = [
  { value: 'en', label: 'English' },
  { value: 'zh-cn', label: '中文' },
  { value: 'fr', label: 'Français' },
  { value: 'de', label: 'Deutsch' },
];

const LanguageSettings = ({
  title,
  className,
  value: oldValue = 'en',
  onChange,
}) => {
  const [value, setValue] = useState(oldValue);

  useEffect(() => {
    setValue(oldValue || 'en');
  }, [oldValue]);

  const selectedOption = useMemo(() => {
    return LANGUAGE_OPTIONS.find(option => option.value === value) || LANGUAGE_OPTIONS[0];
  }, [value]);

  const onValueChange = useCallback((newValue) => {
    setValue(newValue);
    onChange && onChange(newValue);
  }, [onChange]);

  return (
    <div className={classnames('language-settings-option w-100 pl-4 pr-4', className)}>
      <div className="language-settings-header text-truncate">{gettext('Language for AI summary')}</div>
      <div className="language-settings-body">
        <CustomizeSelect
          className="language-selector"
          value={selectedOption}
          options={LANGUAGE_OPTIONS}
          placeholder={gettext('Language for summary generated by AI')}
          onChange={onValueChange}
        />
      </div>
    </div>
  );
};

export default LanguageSettings;
